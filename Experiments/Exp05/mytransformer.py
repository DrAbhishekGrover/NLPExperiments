#Creating Pytorch dataset for self-supervised learning
#Takes tokens and window size and generates dataset for Pytorch model
class TextDataset(Dataset):
    def __init__(self, tokens,seq_len):
        self.tokens=torch.tensor(tokens,dtype=torch.long)
        self.seq_len=seq_len#window size

    def __len__(self):
        return len(self.tokens)-self.seq_len-1

    def __getitem__(self,idx):
        #Input: tokens[0:32], Target: tokens[1:33]
        #Transformer having output from each stream (Sequence to Sequence)
        #This is better learning
        x=self.tokens[idx:idx+self.seq_len]
        y=self.tokens[idx+1:idx+self.seq_len+1]
        return x,y
dataset=TextDataset(all_tokens,window)
#Dataset in the format required by Pytorch
loader=DataLoader(dataset,batch_size=batch_size,shuffle=True, drop_last=True)

#Transformer Model
class myTransformer(nn.Module):
    def __init__(self, vocab_size,embed_dim,nhead,num_layers):
        super().__init__()
        self.embedding=nn.Embedding(num_embeddings=vocab_size,embedding_dim=embed_dim)
        #Positional Encoding
        self.positional=PositionalEncoding(embed_dim,window)
        #Attention layers
        encoder_layers=nn.TransformerEncoderLayer(d_model=embed_dim,nhead=nhead, batch_first=True)
        self.transformer_encoder=nn.TransformerEncoder(encoder_layers,num_layers)
        self.fc=nn.Linear(in_features=embed_dim,out_features=vocab_size)

    def forward(self,x,x_mask,embed_dim):
        x=self.embedding(x)*math.sqrt(embed_dim)
        x=self.positional(x)
        out=self.transformer_encoder(x,x_mask)
        y=self.fc(out)
        return y

mymod=myTransformer(vocab_size=vocab_size,embed_dim=emb_dim,nhead=nhead,num_layers=num_layers).to(device)
optimizer=torch.optim.Adam(params=mymod.parameters(),lr=1e-3)
criterion=nn.CrossEntropyLoss()

mask=nn.Transformer.generate_square_subsequent_mask(window)
mask=mask.to(device)

#Training Loop
for e in range(epochs):
    mymod.train()
    total_loss=0
    for batch_idx,(x,y) in enumerate(loader):
        x,y=x.to(device),y.to(device)#Inputs and outputs
        optimizer.zero_grad()
        #forward pass
        out=mymod(x,mask,emb_dim)
        loss=criterion(out.view(-1,vocab_size),y.view(-1))#Evaluated in batches
        #Backpropagation
        loss.backward()#Calculate gradients
        optimizer.step()#Update weights

        total_loss+=loss.item()
        if batch_idx % 500==0:
            print(f"Epoch {e+1} | Batch {batch_idx}/{len(loader)} | Loss: {loss.item():.2f}")
    avg_loss=total_loss/len(loader)
    print(f"Epoch {e+1} Avg. Loss: {avg_loss:.2f} | Perplexity :{math.exp(avg_loss):.2f}")

